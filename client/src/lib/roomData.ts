export interface CalcResult {
  nights: number;
  accommodationCost: number;
  foodCost: number;
  total: number;
  perNight: number;
}

export interface CalcError {
  error: string;
}

export function calculateAccommodationCost(
  category: RoomCategory,
  checkIn: string,
  checkOut: string,
): { nights: number; cost: number } | CalcError | null {
  if (!checkIn || !checkOut) return null;

  const inDate = new Date(checkIn);
  const outDate = new Date(checkOut);
  const diffMs = outDate.getTime() - inDate.getTime();
  const nights = Math.ceil(diffMs / (1000 * 60 * 60 * 24));

  if (nights < 1) return null;

  const roomInfo = ROOM_DATA[category];
  let cost = 0;

  for (let i = 0; i < nights; i++) {
    const d = new Date(inDate);
    d.setDate(d.getDate() + i);
    const monthNum = d.getMonth() + 1;
    if (monthNum < 6 || monthNum > 9) {
      return { error: "Бронирование доступно только в летний сезон (июнь — сентябрь)" };
    }
    const rate = roomInfo.prices[monthNum];
    if (!rate) return { error: "Нет данных о ценах для выбранного месяца" };
    cost += rate;
  }

  return { nights, cost };
}

export function calculateRoomTotalPrice(
  category: RoomCategory,
  checkIn: string,
  checkOut: string,
  adults: number,
  teens: number,
  children: number,
  toddlers: number = 0,
): CalcResult | CalcError | null {
  const accom = calculateAccommodationCost(category, checkIn, checkOut);
  if (!accom) return null;
  if ("error" in accom) return accom;

  const foodCost = calculateFoodCost(adults, teens, children, toddlers, accom.nights);
  const total = accom.cost + foodCost;
  const perNight = Math.round(total / accom.nights);

  return { nights: accom.nights, accommodationCost: accom.cost, foodCost, total, perNight };
}

export function isRoomSuitable(category: RoomCategory, adults: number, teens: number, childrenCount: number, toddlers: number): boolean {
  const info = ROOM_DATA[category];
  if (toddlers > info.maxToddlers) return false;
  const mainGuests = adults + teens + childrenCount;
  return mainGuests <= info.cap;
}

export interface RoomCombo {
  rooms: Array<{ category: RoomCategory; roomCost: number }>;
  totalCapacity: number;
  totalMaxToddlers: number;
  totalPrice: number;
  nights: number;
  label: string;
  why: string;
}

export interface Recommendations {
  primary: RoomCombo | null;
  alternatives: RoomCombo[];
  seasonError: string | null;
}


function comboLabel(rooms: Array<{ category: RoomCategory }>): string {
  const counts: Record<string, number> = {};
  for (const r of rooms) {
    const short = ROOM_DATA[r.category].shortTitle;
    counts[short] = (counts[short] || 0) + 1;
  }
  return Object.entries(counts).map(([name, c]) => c > 1 ? `${c}× ${name}` : name).join(" + ");
}

function guestsLabel(adults: number, children: number, teens: number): string {
  const parts: string[] = [];
  if (adults > 0) parts.push(`${adults} взр.`);
  if (teens > 0) parts.push(`${teens} подр.`);
  if (children > 0) parts.push(`${children} дет.`);
  return parts.join(", ");
}

function comboSignature(combo: RoomCombo): string {
  const sorted = [...combo.rooms].map(r => r.category).sort();
  return sorted.join("|");
}

export function generateRecommendations(
  checkIn: string,
  checkOut: string,
  adults: number,
  teens: number,
  children: number,
  toddlers: number,
): Recommendations {
  const totalMain = adults + teens + children;

  if (checkIn && new Date(checkIn + "T00:00:00").getMonth() <= 5) {
    return { primary: null, alternatives: [], seasonError: "Бронирование на июнь временно недоступно. Выберите даты с 1 июля." };
  }

  if (hasSeptemberInRange(checkIn, checkOut)) {
    return { primary: null, alternatives: [], seasonError: "Бронирование на сентябрь временно недоступно. Выберите даты до 31 августа." };
  }

  const testCalc = calculateAccommodationCost(roomCategories[0], checkIn, checkOut);
  if (testCalc && "error" in testCalc) {
    return { primary: null, alternatives: [], seasonError: testCalc.error };
  }
  if (!testCalc) {
    return { primary: null, alternatives: [], seasonError: null };
  }

  const nights = testCalc.nights;
  const foodCost = calculateFoodCost(adults, teens, children, toddlers, nights);

  const roomAccomCosts: Record<RoomCategory, number> = {} as any;
  for (const cat of roomCategories) {
    const rc = calculateAccommodationCost(cat, checkIn, checkOut);
    if (rc && !("error" in rc)) roomAccomCosts[cat] = rc.cost;
  }

  type RoomUnit = { category: RoomCategory; cap: number; maxToddlers: number; cost: number; count: number };
  const availableUnits: RoomUnit[] = roomCategories
    .filter(cat => cat in roomAccomCosts)
    .map(cat => ({
      category: cat,
      cap: ROOM_DATA[cat].cap,
      maxToddlers: ROOM_DATA[cat].maxToddlers,
      cost: roomAccomCosts[cat],
      count: ROOM_DATA[cat].count,
    }))
    .sort((a, b) => b.cap - a.cap);

  const allCombos: RoomCombo[] = [];
  const MAX_ROOMS = 4;

  function search(
    idx: number,
    selected: RoomUnit[],
    capSum: number,
    toddlerCap: number,
    costSum: number,
    usedCounts: Record<string, number>,
  ) {
    if (capSum >= totalMain && toddlerCap >= toddlers) {
      allCombos.push({
        rooms: selected.map(u => ({ category: u.category, roomCost: u.cost })),
        totalCapacity: capSum,
        totalMaxToddlers: toddlerCap,
        totalPrice: costSum + foodCost,
        nights,
        label: comboLabel(selected.map(u => ({ category: u.category }))),
        why: "",
      });
      return;
    }
    if (selected.length >= MAX_ROOMS) return;

    for (let i = idx; i < availableUnits.length; i++) {
      const unit = availableUnits[i];
      const used = usedCounts[unit.category] || 0;
      if (used >= unit.count) continue;

      const newCap = capSum + unit.cap;
      const newToddler = toddlerCap + unit.maxToddlers;
      const newCost = costSum + unit.cost;

      usedCounts[unit.category] = used + 1;
      selected.push(unit);

      search(i, selected, newCap, newToddler, newCost, usedCounts);

      selected.pop();
      usedCounts[unit.category] = used;
    }
  }

  search(0, [], 0, 0, 0, {});

  if (allCombos.length === 0) {
    return { primary: null, alternatives: [], seasonError: null };
  }

  allCombos.sort((a, b) => {
    if (a.rooms.length !== b.rooms.length) return a.rooms.length - b.rooms.length;
    const overA = a.totalCapacity - totalMain;
    const overB = b.totalCapacity - totalMain;
    if (overA !== overB) return overA - overB;
    return a.totalPrice - b.totalPrice;
  });

  const gl = guestsLabel(adults, children, teens);

  const byRoomCount = new Map<number, RoomCombo[]>();
  for (const c of allCombos) {
    const key = c.rooms.length;
    if (!byRoomCount.has(key)) byRoomCount.set(key, []);
    byRoomCount.get(key)!.push(c);
  }

  const sortedCounts = Array.from(byRoomCount.keys()).sort((a, b) => a - b);
  const minActualRooms = sortedCounts[0];
  const comfortMinRooms = Math.ceil(totalMain / 2);

  const primary = allCombos[0];
  primary.why = primary.rooms.length === 1
    ? `Оптимальный номер для ${gl}`
    : `Лучшая комбинация номеров для размещения ${gl}`;

  const MAX_ALT = 6;

  const seen = new Set<string>();
  seen.add(comboSignature(primary));

  const alternatives: RoomCombo[] = [];

  function addAlternative(combo: RoomCombo, why: string): boolean {
    const sig = comboSignature(combo);
    if (seen.has(sig)) return false;
    if (combo.label === primary.label) return false;
    seen.add(sig);
    combo.why = why;
    alternatives.push(combo);
    return true;
  }

  const sameCountGroup = (byRoomCount.get(minActualRooms) || []).filter(c => c !== primary);

  for (const c of sameCountGroup) {
    if (alternatives.length >= 3) break;
    const why = c.rooms.length === 1
      ? (c.totalCapacity > primary.totalCapacity ? "Более просторный номер" : "Альтернативная категория")
      : (c.totalPrice < primary.totalPrice ? "Более бюджетный вариант" : "Баланс комфорта и цены");
    addAlternative(c, why);
  }

  for (const level of sortedCounts) {
    if (level <= minActualRooms) continue;
    if (alternatives.length >= MAX_ALT) break;
    const group = byRoomCount.get(level) || [];
    let added = 0;
    for (const c of group) {
      if (alternatives.length >= MAX_ALT) break;
      if (added >= 2) break;
      if (addAlternative(c, "Больше личного пространства")) added++;
    }
  }

  if (alternatives.length < MAX_ALT) {
    for (const c of sameCountGroup) {
      if (alternatives.length >= MAX_ALT) break;
      const why = c.rooms.length === 1
        ? (c.totalCapacity > primary.totalCapacity ? "Более просторный номер" : "Альтернативная категория")
        : (c.totalPrice < primary.totalPrice ? "Более бюджетный вариант" : "Баланс комфорта и цены");
      addAlternative(c, why);
    }
  }

  return { primary, alternatives: alternatives.slice(0, MAX_ALT), seasonError: null };
}
